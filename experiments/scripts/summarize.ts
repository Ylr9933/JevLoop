/**
 * Summarize runs: `experiments/log/` -> `experiments/result/`, one direction
 * only, by the hand of nobody but this script. PROTOCOL.md §6: a table
 * without the command that generated it equals a table without logs, so
 * both outputs carry the command line at the top.
 *
 *   result/direct-sweep.csv   one row per run, joinable on run_id
 *   result/direct-sweep.md    the readable table + provenance
 *
 * Missing or partial runs are included and marked via their exit.json —
 * dropping them would be selective reporting (PROTOCOL §4).
 *
 * @module JevLoop/summarize
 */

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

interface ResultRecord {
  run_id: string
  dataset: string
  arm: string
  model: { id: string }
  success: boolean
  input_tokens_uncached: number
  input_tokens_cached: number
  output_tokens_visible: number
  output_tokens_reasoning: number
  usd: number
  time: { wall_ms: number }
  failure_class: string | null
}

interface RunAggregate {
  run_id: string
  dataset: string
  arm: string
  model: string
  tasks: number
  succeeded: number
  accuracy: number
  failures: Record<string, number>
  tokens_in: number
  tokens_out: number
  usd: number
  wall_mean_ms: number
  completed: boolean | null
}

function readJson(path: string): any {
  return JSON.parse(readFileSync(path, 'utf8'))
}

/** Every run directory under experiments/log/, oldest last by name sort. */
function listRuns(): string[] {
  const logRoot = join(new URL('..', import.meta.url).pathname, 'log')
  const out: string[] = []
  for (const dataset of readdirSync(logRoot, { withFileTypes: true })) {
    if (!dataset.isDirectory()) continue
    const armRoot = join(logRoot, dataset.name)
    for (const arm of readdirSync(armRoot, { withFileTypes: true })) {
      if (!arm.isDirectory()) continue
      const runRoot = join(armRoot, arm.name)
      for (const run of readdirSync(runRoot, { withFileTypes: true })) {
        if (run.isDirectory()) out.push(join(runRoot, run.name))
      }
    }
  }
  return out.sort()
}

/** Fold one run dir into one aggregate row. Empty runs are skipped loudly. */
function aggregate(dir: string): RunAggregate | null {
  const path = join(dir, 'results.jsonl')
  let raw: string
  try {
    raw = readFileSync(path, 'utf8')
  } catch {
    return null
  }
  const rows = raw.split('\n').filter((l) => l.trim() !== '').map((l) => JSON.parse(l) as ResultRecord)
  if (rows.length === 0) return null
  const datasets = new Set(rows.map((r) => r.dataset))
  if (datasets.size > 1) throw new Error(`run dir ${dir} mixes datasets, refusing to summarize`)
  let completed: boolean | null = null
  try {
    completed = readJson(join(dir, 'exit.json')).completed
  } catch {
    completed = null
  }
  const failureTally: Record<string, number> = {}
  for (const r of rows) {
    if (r.failure_class) failureTally[r.failure_class] = (failureTally[r.failure_class] ?? 0) + 1
  }
  const first = rows[0]!
  return {
    run_id: first.run_id,
    dataset: first.dataset,
    arm: first.arm,
    model: first.model.id,
    tasks: rows.length,
    succeeded: rows.filter((r) => r.success).length,
    accuracy: rows.filter((r) => r.success).length / rows.length,
    failures: failureTally,
    tokens_in: rows.reduce((s, r) => s + r.input_tokens_uncached + r.input_tokens_cached, 0),
    tokens_out: rows.reduce((s, r) => s + r.output_tokens_visible + r.output_tokens_reasoning, 0),
    usd: rows.reduce((s, r) => s + r.usd, 0),
    wall_mean_ms: rows.reduce((s, r) => s + r.time.wall_ms, 0) / rows.length,
    completed,
  }
}

const OUT_DIR = join(new URL('..', import.meta.url).pathname, 'result')
const CMD = 'node --experimental-strip-types experiments/scripts/summarize.ts'

const results = listRuns().map(aggregate).filter((r): r is RunAggregate => r !== null)

if (results.length === 0) {
  process.stdout.write('no runs found under experiments/log/\n')
} else {
  mkdirSync(OUT_DIR, { recursive: true })
  const csv = [
    '# generated by: ' + CMD,
    'run_id,dataset,arm,model,tasks,succeeded,accuracy,tokens_in,tokens_out,usd,wall_mean_ms,completed',
    ...results.map((r) =>
      [r.run_id, r.dataset, r.arm, r.model, r.tasks, r.succeeded, r.accuracy.toFixed(4), r.tokens_in, r.tokens_out, r.usd.toFixed(6), Math.round(r.wall_mean_ms), r.completed].join(','),
    ),
  ].join('\n') + '\n'
  writeFileSync(join(OUT_DIR, 'direct-sweep.csv'), csv)

  const lines = [
    '# Direct sweep (auto-generated — do not edit by hand)',
    '',
    `Generated by \`${CMD}\` from \`experiments/log/\`. Every row points at a run_id;`,
    'the log dir behind each id holds cmd.txt / meta.json / results.jsonl / usage.json.',
    '',
    '| run | dataset | arm | model | tasks | acc | tokens in | tokens out | wall mean | completed |',
    '| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | --- |',
  ]
  for (const r of results) {
    lines.push(
      `| ${r.run_id} | ${r.dataset} | ${r.arm} | ${r.model} | ${r.tasks} | ${(r.accuracy * 100).toFixed(1)}% | ${r.tokens_in} | ${r.tokens_out} | ${Math.round(r.wall_mean_ms)}ms | ${r.completed === true ? 'yes' : r.completed === false ? 'partial' : 'unknown'} |`,
    )
  }
  for (const r of results) {
    const f = Object.entries(r.failures)
    if (f.length > 0) lines.push(`- failures in ${r.run_id}: ${f.map(([k, v]) => `${k}=${v}`).join(', ')}`)
  }
  lines.push('')
  writeFileSync(join(OUT_DIR, 'direct-sweep.md'), lines.join('\n'))
  process.stdout.write(`wrote result/direct-sweep.csv and result/direct-sweep.md (${results.length} runs)\n`)
}
